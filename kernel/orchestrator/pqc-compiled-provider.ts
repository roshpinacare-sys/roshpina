/**
 * lib/orchestrator/pqc-compiled-provider.ts — Compiled PQC Provider Wrappers
 *
 * PURPOSE
 * -------
 * Real ML-DSA-44 npm packages (ml-dsa WASM, @noble/post-quantum, OQS bindings)
 * do NOT export a plain `Uint8ArraySigner` interface. They expose lower-level
 * APIs that require keypair generation, then sign(message, secretKey) and
 * verify(signature, message, publicKey).
 *
 * This module wraps those real compiled providers into `Uint8ArraySigner`,
 * which is the interface `adaptPqcProvider` expects. When a real package is
 * installed, `tryLoadWasmModule` / `tryLoadOqsModule` detect it, wrap it,
 * and return a fully-functional provider that passes `MlDsaProviderConformanceSuite`.
 *
 * SUPPORTED MODULE SHAPES
 * -----------------------
 * 1. ml-dsa style:  { keyGen() → {secretKey,publicKey}, sign(msg,sk), verify(sig,msg,pk) }
 * 2. noble style:    { keygen() → {secretKey,publicKey}, sign(msg,sk), verify(sig,msg,pk) }
 * 3. OQS class:     class Signature { constructor(alg), keypair(), sign(msg,sk), verify(msg,sig,pk) }
 *
 * Zero external dependencies — wrapping code is pure TypeScript. The actual
 * compiled primitive lives in the externally-installed module.
 *
 * Both wrapper classes expose the real public key generated by the compiled
 * module's keygen as `publicKey` (PQC sub-step 5) — `adaptPqcProvider` uses
 * it to derive a stable `kid`, the same way `Ed25519Signer` derives one from
 * its public key. The secret key never leaves the instance.
 */

import { SignerError, ML_DSA_44_SIGNATURE_BYTES } from "./signer.ts";
import type { Uint8ArraySigner } from "./pqc-adapter.ts";

// ─── ml-dsa / @noble/post-quantum / pqcrypto style ───────────────────────────

/** Shape of a compiled ml-dsa / @noble/post-quantum module. */
export interface MlDsaCompiledModule {
  keyGen?(): { secretKey: Uint8Array; publicKey: Uint8Array };
  keygen?(): { secretKey: Uint8Array; publicKey: Uint8Array };
  sign(message: Uint8Array, secretKey: Uint8Array, ctx?: Uint8Array): Uint8Array;
  verify(signature: Uint8Array, message: Uint8Array, publicKey: Uint8Array, ctx?: Uint8Array): boolean;
}

/** Guard: does `mod` look like a compiled ml-dsa / noble module? */
export function isMlDsaCompiledModule(mod: unknown): mod is MlDsaCompiledModule {
  if (typeof mod !== "object" || mod === null) return false;
  const m = mod as any;
  return (
    typeof m.sign === "function" &&
    typeof m.verify === "function" &&
    (typeof m.keyGen === "function" || typeof m.keygen === "function")
  );
}

/**
 * Wraps a compiled ml-dsa / noble module into a `Uint8ArraySigner`.
 *
 * Generates a keypair on construction, then uses it for every sign/verify.
 * The provider is stateful: the same instance signs and verifies with the
 * same keypair.
 */
export class MlDsaCompiledProvider implements Uint8ArraySigner {
  private readonly mod: MlDsaCompiledModule;
  private readonly secretKey: Uint8Array;
  /** Real public verification key from the compiled module's keygen — safe to expose for kid derivation. */
  readonly publicKey: Uint8Array;

  constructor(mod: MlDsaCompiledModule) {
    if (!isMlDsaCompiledModule(mod)) {
      throw new SignerError(
        "PROVIDER_REQUIRED",
        "Module is not a recognized ML-DSA compiled module (expected keyGen/keygen + sign + verify)",
      );
    }
    const keys = mod.keyGen?.() ?? mod.keygen?.();
    if (
      !keys ||
      !(keys.secretKey instanceof Uint8Array) ||
      !(keys.publicKey instanceof Uint8Array)
    ) {
      throw new SignerError(
        "PROVIDER_REQUIRED",
        "Compiled ML-DSA module key generation returned invalid keys",
      );
    }
    this.mod = mod;
    this.secretKey = keys.secretKey;
    this.publicKey = keys.publicKey;
  }

  sign(msg: Uint8Array): Uint8Array {
    const sig = this.mod.sign(msg, this.secretKey);
    // Some WASM providers may append context bytes; trim to FIPS-204 length if oversized.
    if (sig.length > ML_DSA_44_SIGNATURE_BYTES) {
      return sig.slice(0, ML_DSA_44_SIGNATURE_BYTES);
    }
    return sig;
  }

  verify(msg: Uint8Array, sig: Uint8Array): boolean {
    try {
      return this.mod.verify(sig, msg, this.publicKey);
    } catch {
      return false;
    }
  }
}

// ─── OQS class style (@open-quantum-safe/liboqs, liboqs-js) ──────────────────

/** Instance shape returned by an OQS Signature class. */
export interface OqsSignatureInstance {
  keypair(): { secretKey: Uint8Array; publicKey: Uint8Array };
  sign(message: Uint8Array, secretKey: Uint8Array): Uint8Array;
  verify(message: Uint8Array, signature: Uint8Array, publicKey: Uint8Array): boolean;
}

/** Constructor shape for an OQS Signature class. */
export interface OqsSignatureClass {
  new(algorithm: string): OqsSignatureInstance;
}

/** Guard: does `mod` look like an OQS Signature constructor? */
export function isOqsSignatureClass(mod: unknown): mod is OqsSignatureClass {
  if (typeof mod !== "function") return false;
  const proto = (mod as any).prototype;
  return (
    proto &&
    typeof proto.keypair === "function" &&
    typeof proto.sign === "function" &&
    typeof proto.verify === "function"
  );
}

/**
 * Wraps an OQS-style class module into a `Uint8ArraySigner`.
 *
 * Tries "ML-DSA-44" first, then falls back to "Dilithium2" (the pre-standard
 * name used by many OQS bindings). Fail-closed if neither instantiates.
 */
export class MlDsaOqsClassProvider implements Uint8ArraySigner {
  private readonly instance: OqsSignatureInstance;
  private readonly secretKey: Uint8Array;
  /** Real public verification key from the OQS keypair — safe to expose for kid derivation. */
  readonly publicKey: Uint8Array;

  constructor(cls: OqsSignatureClass, algorithm = "ML-DSA-44") {
    let instance: OqsSignatureInstance;
    try {
      instance = new cls(algorithm);
    } catch {
      // Some OQS bindings use "Dilithium2" as the algorithm name.
      try {
        instance = new cls("Dilithium2");
      } catch {
        throw new SignerError(
          "PROVIDER_REQUIRED",
          `OQS Signature class failed to instantiate with algorithm "${algorithm}" or "Dilithium2"`,
        );
      }
    }
    const keys = instance.keypair();
    if (
      !keys ||
      !(keys.secretKey instanceof Uint8Array) ||
      !(keys.publicKey instanceof Uint8Array)
    ) {
      throw new SignerError(
        "PROVIDER_REQUIRED",
        "OQS keypair generation returned invalid keys",
      );
    }
    this.instance = instance;
    this.secretKey = keys.secretKey;
    this.publicKey = keys.publicKey;
  }

  sign(msg: Uint8Array): Uint8Array {
    const sig = this.instance.sign(msg, this.secretKey);
    if (sig.length > ML_DSA_44_SIGNATURE_BYTES) {
      return sig.slice(0, ML_DSA_44_SIGNATURE_BYTES);
    }
    return sig;
  }

  verify(msg: Uint8Array, sig: Uint8Array): boolean {
    try {
      return this.instance.verify(msg, sig, this.publicKey);
    } catch {
      return false;
    }
  }
}

// ─── Unified wrapper ─────────────────────────────────────────────────────────

/**
 * Wrap any recognized compiled PQC module into a `Uint8ArraySigner`.
 *
 * Tries module shapes in order:
 *   1. ml-dsa / noble / pqcrypto style (keyGen/keygen object)
 *   2. OQS class style (new Signature(alg))
 *   3. Already a plain Uint8ArraySigner (pass-through)
 *
 * Returns `undefined` if the module shape is not recognized or initialization fails.
 * This is the single entry-point used by `tryLoadOqsModule` and `tryLoadWasmModule`.
 */
export function wrapCompiledModule(mod: unknown): Uint8ArraySigner | undefined {
  // 1. ml-dsa / noble / pqcrypto compiled module
  if (isMlDsaCompiledModule(mod)) {
    try {
      return new MlDsaCompiledProvider(mod);
    } catch {
      return undefined;
    }
  }

  // 2. OQS class module
  if (isOqsSignatureClass(mod)) {
    try {
      return new MlDsaOqsClassProvider(mod);
    } catch {
      return undefined;
    }
  }

  // 3. Naive Uint8ArraySigner pass-through (custom / future modules)
  if (
    typeof mod === "object" &&
    mod !== null &&
    typeof (mod as any).sign === "function" &&
    typeof (mod as any).verify === "function"
  ) {
    return mod as Uint8ArraySigner;
  }

  return undefined;
}
